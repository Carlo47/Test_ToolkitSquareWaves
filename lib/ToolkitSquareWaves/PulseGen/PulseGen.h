/**
 * Class      PulseGen
 *
 * Author     2026-11-09 Charles Geiser (www.dodeka.ch)
 *
 * Purpose    Implements a class `PulseGen` which generates square-wave signals
 *            up to over 10 kHz with adjustable pulse width or duty cycle.
 *            If two or more generators are started nearly simultaneously,
 *            a phase shift can be specified for each one.
 *            The polarity of the output signal can be inverted.
 *            The three different constructors make use of polymorphism.
 *
 * Remarks    gpio_set_level(_pin, (micros() - _usPhase) % _usPeriod < _usPulseWidth ? HIGH : LOW);
 *
 *            The square-wave pulses are generated by a simple modulo operation
 *            on the micros() counter. Since this operation is relatively slow,
 *            this explains the practical upper frequency limit of about 10 kHz.
 */
#pragma once
#include <Arduino.h>

namespace SquareWave
{
  class PulseGen
  {
    public:
      // `Heartbeat: defaults to 1 beat/sec with 5% duty
      PulseGen(gpio_num_t pin) : _pin(pin)
      {
        gpio_reset_pin(_pin);
        gpio_set_direction((gpio_num_t) _pin, GPIO_MODE_OUTPUT);
      }

      // Pulse with given period and pulse width, phase defaults to 0°
      PulseGen(gpio_num_t pin, uint32_t usPeriod, uint32_t usPulseWidth, uint32_t degPhase = 0)
          : _pin(pin), _usPeriod(usPeriod), _usPulseWidth(usPulseWidth), _degPhase(degPhase)
      {
        gpio_reset_pin(_pin);
        gpio_set_direction(_pin, GPIO_MODE_OUTPUT);
        _usPhase = _usPeriod / 360 * _degPhase;
      }

      // n beats in m seconds with duty 0..99 % and a phase of -359..359 deg
      PulseGen(gpio_num_t pin, uint32_t nBeats, uint32_t mSecs, float dutyCycle, uint32_t degPhase = 0)
          : _pin(pin), _usPeriod(1'000'000 * mSecs / nBeats), _degPhase(degPhase)
      {
        // pinMode(_pin, OUTPUT);
        gpio_reset_pin(_pin);
        gpio_set_direction(_pin, GPIO_MODE_OUTPUT);
        dutyCycle     = (dutyCycle < 0.0 || dutyCycle > 100.0) ? 50.0 : dutyCycle;
        _usPhase      = _usPeriod / 360 * _degPhase;
        _usPulseWidth = _usPeriod * (dutyCycle / 100.0F);
      }

      void loop();
      void on();
      void off();
      void setPhase(uint32_t degPhase);
      void setPeriod(uint32_t usPeriod);
      void setPulseWidth(uint32_t usPulseWidth);
      void setInvertedOutput(bool inverted);

    private:
      gpio_num_t _pin;
      uint32_t   _usPeriod     = 1'000'000; // 1 sec
      uint32_t   _usPhase      = 0;
      uint32_t   _degPhase     = 0;      // -359..359
      uint32_t   _usPulseWidth = 50'000; // 50 ms = 5% duty
      uint32_t   _msPrevious   = 0;
      bool       _isEnabled    = false;
      bool       _isInverted   = false;
  };
} // namespace SquareWave